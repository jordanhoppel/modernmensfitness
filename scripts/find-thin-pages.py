#!/usr/bin/env python3
"""Find templated stub pages and write src/data/thinPages.json (pages the layout marks noindex, follow).

  npx astro build && python3 -I scripts/find-thin-pages.py

A page is flagged when BOTH are true:
  - its main text is under MAX_WORDS words, and
  - at least MIN_SHARED of its 6-word phrases also appear in another page (Jaccard similarity of
    6-word shingles, i.e. it is a near-copy of a sibling with the title swapped).
Pages that redirect away (public/_redirects) are ignored. Re-run after adding or rewriting articles:
a rewritten page drops off the list by itself, so it becomes indexable again on the next deploy.
"""
import html, itertools, json, os, re, sys

MAX_WORDS = 600
MIN_SHARED = 0.5
SHINGLE = 6
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
dist = os.path.join(root, "dist")

redirected = set()
with open(os.path.join(root, "public", "_redirects")) as f:
    for line in f:
        p = line.split()
        if len(p) >= 3 and p[0].startswith("/") and p[-1] in ("301", "302"):
            redirected.add(p[0].rstrip("/") or "/")

def main_text(path):
    h = open(path, encoding="utf-8").read()
    m = re.search(r"<main[^>]*>(.*?)</main>", h, re.S)
    t = m.group(1) if m else h
    t = re.sub(r"<(script|style)[^>]*>.*?</\1>", "", t, flags=re.S)
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", t))).strip()

def shingles(text):
    w = re.findall(r"[a-z0-9']+", text.lower())
    return {tuple(w[i:i + SHINGLE]) for i in range(len(w) - SHINGLE + 1)}

pages = {}
for dirpath, _, files in os.walk(dist):
    if "index.html" not in files:
        continue
    slug = "/" + os.path.relpath(dirpath, dist).replace(os.sep, "/") + "/"
    slug = "/" if slug == "/./" else slug
    if slug.startswith("/_astro") or slug.rstrip("/") in redirected or slug == "/404/":
        continue
    pages[slug] = main_text(os.path.join(dirpath, "index.html"))

words = {s: len(t.split()) for s, t in pages.items()}
sh = {s: shingles(t) for s, t in pages.items()}
twin = {s: 0.0 for s in pages}
for a, b in itertools.combinations(pages, 2):
    A, B = sh[a], sh[b]
    if A and B:
        j = len(A & B) / len(A | B)
        twin[a] = max(twin[a], j)
        twin[b] = max(twin[b], j)

thin = sorted(s for s in pages if words[s] < MAX_WORDS and twin[s] >= MIN_SHARED)
out = {
    "note": "Generated by scripts/find-thin-pages.py. Pages listed here render <meta robots noindex, follow> and are left out of the sitemaps.",
    "criteria": {"max_words": MAX_WORDS, "min_shared_phrase_similarity": MIN_SHARED, "shingle_words": SHINGLE},
    "count": len(thin),
    "paths": thin,
}
with open(os.path.join(root, "src", "data", "thinPages.json"), "w") as f:
    json.dump(out, f, indent=1)
print(f"pages analysed: {len(pages)} | flagged thin: {len(thin)}")
